def to_jp(s: Optional[str]) -> str:
    """简体/繁体 → 日文新字体；**整串命中中文线路名时直接换官方名**。"""
    t = (s or "").strip()
    if t in ZH2JP_ALIAS:
        return ZH2JP_ALIAS[t]
    if not t:
        return ""
    return "".join(CN2JP.get(c, c) for c in t)


def line_zh(name: Optional[str]) -> str:
    """线路的显示用中文名（**不落库**，要就现算）。"""
    if not name:
        return ""
    return LINE_ZH.get(str(name)) or to_zh(name)


def zh_line_ids(db, q: str) -> list:
    """**中文线路名 → 线路 id**（中文名里含查询串的那些）。

    为什么要这个：汉字映射解决不了 ノ/假名（「丸之内线」↔「丸ノ内線」），
    所以拿"算出来的中文名"再匹配一遍；131 条线在内存里比，成本可忽略。
    """
    from app.models import BdLine
    q = (q or "").strip()
    if not q:
        return []
    out = []
    for (lid, name) in db.query(BdLine.id, BdLine.name).all():
        zh = line_zh(name)
        if zh and q in zh:
            out.append(lid)
    return out


def _old_to_jp(s: Optional[str]) -> str:
    """简体/繁体 → 日文新字体（**搜索前把用户输入转成数据的形态**）。

    ⚠️ 整串逐字映射，已为日文形的字不受影响（幂等）。
    """
    if not s:
        return ""
    return "".join(CN2JP.get(c, c) for c in str(s))


def to_zh(s: Optional[str]) -> str:
    """日文新字体 → 简体（显示/别名用；**不落库**，要就现算）。"""
    if not s:
        return ""
    t = str(s)
    if t in LINE_ZH_ALIAS:
        return LINE_ZH_ALIAS[t]
    # ⚠️ 反向表用 setdefault：**先出现的简体优先**（dict 里简体写在繁体前面）；
    #    最后一个 dict 推导（`{v: k ...}`）会随机取到繁体，导致显示成"澀谷"这种。
    rev = {}
    for zh, jp in CN2JP.items():
        rev.setdefault(jp, zh)
    for jp, zh in (("渋", "涩"), ("浜", "滨"), ("桜", "樱"), ("葉", "叶"),
                   ("線", "线"), ("東", "东"), ("鉄", "铁"),
                   ("車", "车"), ("馬", "马"), ("島", "岛"), ("鉄", "铁")):
        rev[jp] = zh
    return "".join(rev.get(c, c) for c in t)


def search_variants(q: Optional[str]) -> list:
    """搜索用的候选串：**原串 + 转日文形 + 转中文形**（去重，短的在后无所谓）。

    外层 `LIKE %v%` 逐个 OR 上去 —— 这样中/日/繁三种输入都能命中同一批数据。
    """
    q = (q or "").strip()
    if not q:
        return []
    out = []
    for v in (to_jp(q), q, to_zh(q)):
        if v and v not in out:
            out.append(v)
    return out


