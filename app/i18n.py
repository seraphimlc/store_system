def translate(text: str, lang: Optional[str] = None) -> str:
    """取译文：ja 查字典（未收录返回原文），zh/其他返回原文。"""
    lang = lang or CURRENT_LANG.get()
    if lang == "ja":
        return _JA.get(text, text)
    return text


def t(text: str) -> str:
    """Jinja2 全局函数：按当前请求语言翻译。"""
    return translate(text)


def resolve_lang(query: str = "", cookie: str = "",
                  user_lang: str = "", accept: str = "") -> str:
    """语言解析：URL ?lang= → cookie → 账号级 → Accept-Language → 默认。"""
    for v in (query, cookie, user_lang):
        v = (v or "").strip().lower()
        if v in LANGS:
            return v
    if accept:
        # 浏览器首选语言
        for part in accept.split(","):
            code = part.strip().split(";")[0].split("-")[0].lower()
            if code in LANGS:
                return code
    return DEFAULT_LANG


# ---------------- 带参数的消息（给"操作反馈"用，不走模板 t()） ----------------

def render_msg(key: str, *args, lang: str = "") -> str:
    """把带参数的消息按当前语言渲染。

    ⚠️ 为什么不用模板的 `t()`：路由里的反馈是**拼好再通过 URL/上下文传出去**的
    （`?msg=已改派 3 个任务`），里面带数字；`t()` 只认精确 key。
    所以：`render_msg("已改派 %d 个任务", 3)` → 按语言取模板串再 `.format()`。
    """
    from app.i18n import translate
    lg = lang or CURRENT_LANG.get()          # ⚠️ 别用 dir()（函数里查的是局部名）
    tpl = translate(key, lg) or key
    if not args:
        return tpl
    try:
        return tpl % args
    except (TypeError, ValueError):
        try:
            return tpl.format(*args)
        except Exception:                     # noqa: BLE001
            return key % args
